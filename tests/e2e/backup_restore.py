import asyncio, os, sys, zipfile, json, hashlib
from playwright.async_api import async_playwright
from _common import BASE, FIXTURES, OUT, ok  # noqa: E402  (shared setup: server address, sample files, output folder)

F=FIXTURES
async def notes(pg): await pg.wait_for_timeout(120); return await pg.evaluate("JSON.parse(localStorage.getItem('webnotes:notes')||'[]')")
async def asset_count(pg): return await pg.evaluate("new Promise(r=>{const q=indexedDB.open('webnotes-assets',1);q.onupgradeneeded=()=>q.result.createObjectStore('files',{keyPath:'id'});q.onsuccess=()=>{const g=q.result.transaction('files').objectStore('files').getAll();g.onsuccess=()=>r(g.result.map(a=>[a.id,a.size]))}})")
async def main():
  async with async_playwright() as p:
    b=await p.chromium.launch()
    A=await (await b.new_context(viewport={"width":1400,"height":900}, accept_downloads=True)).new_page()
    errs=[]; A.on("pageerror", lambda e: errs.append(str(e)))
    await A.goto(BASE); await A.wait_for_timeout(900)
    # a real notebook: Word doc with images, PDF pages, an attachment, a sketch, folders + tags, a saved template
    await A.click(".list-head button:has-text('New')")
    async with A.expect_file_chooser() as fc: await A.click("text=Import file…")
    await (await fc.value).set_files([os.path.join(F,x) for x in ["Project_Brief.docx","Physics_Notes.pdf","archive.zip","pic.png"]])
    await A.click("button:has-text('Import'):not(:has-text('file'))"); await A.wait_for_function("!document.querySelector('.modal')", timeout=60000)
    await A.locator(".note-card").filter(has_text="Project Brief").first.click(); await A.wait_for_timeout(400)
    await A.fill("input[placeholder='Folder']", "Work"); await A.keyboard.press("Tab")
    await A.fill("input[placeholder='Add tag']", "brief"); await A.keyboard.press("Enter"); await A.wait_for_timeout(200)
    await A.evaluate("""localStorage.setItem('webnotes:templates', JSON.stringify([{id:'t1',name:'My layout',cat:'My layouts',kind:'page',paper:'blank',els:[{id:'e1',t:'rect',x:0,y:0,x2:100,y2:50,c:'auto',w:2}],createdAt:Date.now()}]))""")
    before=await notes(A); assets_before=await asset_count(A)
    ok("notebook set up", len(before)>=4 and len(assets_before)>=5, f"{len(before)} notes, {len(assets_before)} files")
    await A.click("[aria-label='Settings']"); await A.click(".tabs button:has-text('Backup')")
    async with A.expect_download() as d: await A.click("button:has-text('Download full backup')")
    path=os.path.join(OUT,"full.webnotes"); await (await d.value).save_as(path); await A.wait_for_timeout(300)
    ok("backup made, status shown", await A.locator(".status-line:has-text('Saved webnotes-backup')").count()==1)
    z=zipfile.ZipFile(path); man=json.loads(z.read("manifest.json"))
    ok("backup contains notes, every file, templates", man["counts"]["notes"]==len(before) and man["counts"]["files"]==len(assets_before) and man["counts"]["templates"]==1, str(man["counts"]))
    ok("every file has a fingerprint that matches", all(hashlib.sha256(z.read("files/"+f["id"])).hexdigest()==f["sha256"] for f in man["files"]))
    ok("AI keys not in backup", b"apiKey" not in z.read("settings.json") and "webnotes:ai" not in z.namelist())
    await A.screenshot(path=OUT+"/01-backup.png")
    # ---- a brand-new browser profile
    ctx2=await b.new_context(viewport={"width":1400,"height":900}, accept_downloads=True); B=await ctx2.new_page(); B.on("pageerror", lambda e: errs.append(str(e)))
    await B.goto(BASE); await B.wait_for_timeout(900)
    await B.click("[aria-label='Settings']"); await B.click(".tabs button:has-text('Backup')")
    await B.set_input_files(".modal input[type=file]", path); await B.wait_for_selector(".restore-check", timeout=20000)
    checks=await B.locator(".restore-check li").all_inner_texts()
    ok("checked before restoring", all(c.startswith("✓") for c in checks), str(checks))
    await B.screenshot(path=OUT+"/02-check.png")
    await B.click(".restore-check button:has-text('Restore')"); await B.wait_for_selector(".status-line:has-text('Restored')", timeout=30000)
    msg=await B.locator(".status-line:has-text('Restored')").inner_text()
    ok("restore verified every file", "Every file was read back" in msg, msg)
    await B.screenshot(path=OUT+"/03-restored.png"); await B.click("button:has-text('Done')")
    after=await notes(B); assets_after=await asset_count(B)
    ok("all notes restored", {n["id"] for n in after}=={n["id"] for n in before}, f"{len(after)}")
    ok("all files restored, same sizes", sorted(assets_after)==sorted(assets_before))
    nb={n["title"]:n for n in after}
    ok("folders and tags kept", nb["Project Brief"].get("folder")=="Work" and "brief" in nb["Project Brief"]["tags"])
    ok("templates restored", "My layout" in await B.evaluate("localStorage.getItem('webnotes:templates')"))
    await B.locator(".note-card").filter(has_text="Project Brief").first.click(); await B.wait_for_timeout(900)
    ok("Word pictures show in the new browser", await B.evaluate("Math.max(0,...[...document.querySelectorAll('.rich-doc img, .md img')].map(i=>i.naturalWidth))")>0)
    await B.locator(".note-card").filter(has_text="Physics Notes").first.click(); await B.wait_for_timeout(1500)
    ok("PDF pages show in the new browser", await B.evaluate("[...document.querySelectorAll('svg image')].filter(i=>i.getAttribute('href')?.startsWith('blob:')).length")>=3)
    await B.locator(".note-card").filter(has_text="archive").first.click(); await B.wait_for_timeout(400)
    if await B.locator("[role=radio]:text-is('Preview')").count(): await B.click("[role=radio]:text-is('Preview')")
    async with B.expect_download() as d: await B.locator("a.attachment").first.click()
    p2=os.path.join(OUT,"att.zip"); await (await d.value).save_as(p2)
    ok("attachment downloads byte-for-byte", open(p2,"rb").read()==open(os.path.join(F,"archive.zip"),"rb").read())
    # ---- damaged backup is caught
    bad=os.path.join(OUT,"damaged.webnotes"); zi=zipfile.ZipFile(path); zo=zipfile.ZipFile(bad,"w")
    first=man["files"][0]["id"]
    for it in zi.infolist():
        data=zi.read(it.filename)
        if it.filename=="files/"+first: data=data[:-10]+b"0123456789"
        zo.writestr(it, data)
    zo.close()
    await B.click("[aria-label='Settings']"); await B.click(".tabs button:has-text('Backup')")
    await B.set_input_files(".modal input[type=file]", bad); await B.wait_for_selector(".restore-check", timeout=20000)
    warn=await B.locator(".restore-check li.warn").all_inner_texts()
    ok("damaged file in a backup is detected", any("damaged" in w for w in warn), str(warn))
    await B.screenshot(path=OUT+"/04-damaged.png")
    # not a backup
    junk=os.path.join(OUT,"junk.json"); open(junk,"w").write('{"hello":1}')
    await B.click(".restore-check button:has-text('Cancel')"); await B.set_input_files(".modal input[type=file]", junk); await B.wait_for_selector(".restore-check")
    ok("wrong file is refused", await B.locator(".restore-check button:has-text('Restore')").is_disabled())
    ok("no errors", not errs, ";".join(errs[:2]))
    await b.close()
asyncio.run(main())
