import asyncio, sys, os
from playwright.async_api import async_playwright
from _common import BASE, FIXTURES, OUT, ok  # noqa: E402  (shared setup: server address, sample files, output folder)

F, D = FIXTURES, OUT
async def notes(pg): return await pg.evaluate("JSON.parse(localStorage.getItem('webnotes:notes')||'[]')")
async def cur(pg): return (await notes(pg))[0]
async def new(pg, label):
    await pg.click(".list-head button:has-text('New')"); await pg.click(f".new-menu .menu-item:has(b:text-matches('^{label}'))"); await pg.wait_for_timeout(500)
async def dl(pg, label, path):
    await pg.click("[aria-label='Download as']")
    async with pg.expect_download() as d: await pg.click(f".menu-item:has(b:text-is('{label}'))")
    await (await d.value).save_as(path); return path
async def main():
  async with async_playwright() as p:
    b=await p.chromium.launch(); ctx=await b.new_context(viewport={"width":1500,"height":950}, accept_downloads=True); pg=await ctx.new_page()
    errs=[]; pg.on("pageerror", lambda e: errs.append(str(e))); pg.on("dialog", lambda d: asyncio.ensure_future(d.accept()))
    await pg.goto(BASE); await pg.wait_for_timeout(800)
    await pg.click(".list-head button:has-text('New')"); await pg.wait_for_timeout(200)
    labels=await pg.locator(".new-menu .menu-item b").all_inner_texts(); await pg.screenshot(path=f"{D}/01-new-menu.png"); await pg.keyboard.press("Escape"); await pg.mouse.click(5,940)
    ok("New menu offers every type", all(any(l.startswith(x) for l in labels) for x in ["Document","Markdown","Plain text","Code","Spreadsheet","Scribble page"]), str(labels))
    # ---- Document (rich text)
    await new(pg,"Document"); await pg.fill("input[aria-label='Note title']","Rich doc")
    doc=pg.locator(".rich-doc"); await doc.click()
    await pg.select_option(".rich-bar select","h1"); await pg.keyboard.type("Big heading"); await pg.keyboard.press("Enter")
    await pg.select_option(".rich-bar select","p"); await pg.keyboard.type("Normal "); await pg.keyboard.press("ControlOrMeta+b"); await pg.keyboard.type("bold"); await pg.keyboard.press("ControlOrMeta+b"); await pg.keyboard.type(" words."); await pg.keyboard.press("Enter")
    await pg.click("[aria-label='Bulleted list']"); await pg.keyboard.type("First point"); await pg.keyboard.press("Enter"); await pg.keyboard.type("Second point"); await pg.keyboard.press("Enter"); await pg.keyboard.press("Enter")
    await pg.click("[aria-label='Checklist']"); await pg.wait_for_timeout(100)
    await pg.click("[aria-label='Insert table']"); await pg.wait_for_timeout(300)
    n=await cur(pg); h=n.get("html","")
    ok("Document: no markdown marks, real formatting", n.get("format")=="rich" and "<h1>Big heading</h1>" in h and "<b>bold</b>" in h or "<strong>bold</strong>" in h, h[:200])
    ok("Document: lists, checklist, table", "<ul>" in h and "data-checked" in h and "<table>" in h)
    ok("Document: searchable plain text", "Big heading" in n["body"] and "<" not in n["body"])
    box=await pg.locator(".rich-doc li[data-checked]").first.bounding_box(); await pg.mouse.click(box["x"]+10, box["y"]+box["height"]/2); await pg.wait_for_timeout(200)
    ok("Document: checklist ticks", 'data-checked="true"' in (await cur(pg))["html"])
    await pg.screenshot(path=f"{D}/02-document.png")
    p=await dl(pg,"Word (.docx)",f"{D}/doc.docx"); import docx; dd=docx.Document(p); txt=[x.text for x in dd.paragraphs]
    ok("Document → Word keeps heading/list/table", "Big heading" in txt and "First point" in txt and len(dd.tables)==1, str(txt[:6]))
    # scribble on document
    await pg.click("[role=switch]"); await pg.wait_for_timeout(300)
    ok("Document: Scribble toolbar", await pg.locator(".overlay-chrome button:has-text('Templates')").count()==1 and await pg.locator(".rich-doc[contenteditable=false]").count()==1)
    ov=await pg.locator(".canvas-overlay svg").bounding_box(); await pg.mouse.move(ov["x"]+20,ov["y"]+30); await pg.mouse.down(); await pg.mouse.move(ov["x"]+200,ov["y"]+40,steps=6); await pg.mouse.up(); await pg.click("[role=switch]")
    ok("Document: scribble saved, editing back on", len((await cur(pg)).get("ink",[]))==1 and await pg.locator(".rich-doc[contenteditable=true]").count()==1)
    # ---- Plain text
    await new(pg,"Plain text"); await pg.fill("input[aria-label='Note title']","Plain"); await pg.click("textarea.plain-edit"); await pg.keyboard.type("Line one\n**not bold**")
    n=await cur(pg); ok("Plain text keeps characters as typed", n["format"]=="text" and n["body"]=="Line one\n**not bold**")
    p=await dl(pg,"Text (.txt)",f"{D}/plain.txt"); ok("Plain → .txt", open(p).read()=="Line one\n**not bold**")
    # ---- Code
    await new(pg,"Code"); await pg.fill("input[aria-label='Note title']","script"); await pg.select_option("select[aria-label='Language']","python")
    await pg.click("textarea.code-edit"); await pg.keyboard.type("def hi():\n    return 1")
    await pg.click("[role=radio]:text-is('Highlighted')"); await pg.wait_for_timeout(200)
    ok("Code: highlighted view", await pg.locator(".code-view .hljs-keyword").count()>=1)
    p=await dl(pg,"Code file (.py)",f"{D}/script.py"); ok("Code → .py file", "def hi()" in open(p).read())
    # ---- Spreadsheet
    await new(pg,"Spreadsheet"); await pg.fill("input[aria-label='Note title']","Sheet")
    await pg.locator("[data-cell='0-0']").click()
    for v in ["Item","Cost"]: await pg.keyboard.type(v); await pg.keyboard.press("Tab")
    await pg.locator("[data-cell='1-0']").click(); await pg.keyboard.type("Pens"); await pg.keyboard.press("Tab"); await pg.keyboard.type("30"); await pg.keyboard.press("Enter")
    await pg.locator("[data-cell='2-0']").click(); await pg.keyboard.type("Paper"); await pg.keyboard.press("Tab"); await pg.keyboard.type("12.5"); await pg.keyboard.press("Enter")
    await pg.locator("[data-cell='3-0']").click(); await pg.keyboard.type("Total"); await pg.keyboard.press("Tab"); await pg.keyboard.type("=SUM(B2:B3)"); await pg.keyboard.press("Enter")
    await pg.wait_for_timeout(200)
    ok("Spreadsheet: formula computes", (await pg.locator("[data-cell='3-1']").inner_text()).strip()=="42.5", await pg.locator("[data-cell='3-1']").inner_text())
    await pg.locator("[data-cell='1-1']").click(); await pg.keyboard.type("100"); await pg.keyboard.press("Enter"); await pg.wait_for_timeout(150)
    ok("Spreadsheet: formula updates", (await pg.locator("[data-cell='3-1']").inner_text()).strip()=="112.5")
    await pg.locator("[data-cell='2-2']").click(); await pg.keyboard.type("=B2/0"); await pg.keyboard.press("Enter"); await pg.wait_for_timeout(100)
    ok("Spreadsheet: errors shown", "#DIV/0" in await pg.locator("[data-cell='2-2']").inner_text())
    await pg.click("[aria-label='Add sheet']"); ok("Spreadsheet: second sheet", len((await cur(pg))["sheets"])==2)
    await pg.locator(".sheet-tabs [role=tab]").first.click()
    await pg.screenshot(path=f"{D}/03-sheet.png")
    p=await dl(pg,"Excel (.xlsx)",f"{D}/sheet.xlsx"); import openpyxl; wb=openpyxl.load_workbook(p); ws=wb.worksheets[0]
    ok("Spreadsheet → Excel keeps the formula", ws["B4"].value=="=SUM(B2:B3)" and ws["A2"].value=="Pens" and len(wb.worksheets)==2, str(ws["B4"].value))
    p=await dl(pg,"CSV (.csv)",f"{D}/sheet.csv"); ok("Spreadsheet → CSV values", "Total,112.5" in open(p).read())
    ok("Spreadsheet: searchable", "112.5" in (await cur(pg))["body"])
    # ---- Markdown + change types
    await new(pg,"Markdown"); await pg.fill("input[aria-label='Note title']","Md"); await pg.click("[role=radio]:text-is('Edit')")
    await pg.fill("textarea.source","# Title\n\nSome **bold** text.\n\n| A | B |\n|---|---|\n| 1 | 2 |\n| 3 | 4 |\n")
    await pg.click(".type-btn"); await pg.click(".menu-item:has(b:text-matches('^Spreadsheet'))")
    await pg.wait_for_timeout(300) 
    n=await cur(pg); ok("Markdown table → Spreadsheet (after confirm)", n.get("format")=="sheet" and n["sheets"][0]["rows"][1][:2]==["1","2"], str(n.get("format")))
    await pg.click(".type-btn"); await pg.click(".menu-item:has(b:text-matches('^Document'))"); await pg.wait_for_timeout(300)
    n=await cur(pg); ok("Spreadsheet → Document table", n["format"]=="rich" and "<table>" in n["html"])
    await pg.click(".type-btn"); await pg.click(".menu-item:has(b:text-matches('^Markdown'))"); await pg.wait_for_timeout(500)
    n=await cur(pg); ok("Document → Markdown", n["format"]=="markdown" and "| A | B |" in n["body"].replace("  "," "), n["body"][:80])
    await pg.click(".type-btn"); await pg.click(".menu-item:has(b:text-matches('^Document'))"); await pg.wait_for_timeout(300)
    n=await cur(pg); ok("Markdown → Document", n["format"]=="rich" and "<table>" in n["html"])
    # ---- default type setting
    await pg.click("[aria-label='Settings']"); await pg.select_option("select[aria-label='Type for new notes']","rich"); await pg.click("button:has-text('Done')")
    await pg.click(".list-head button:has-text('New')"); ok("Default type marked in New menu", await pg.locator(".new-menu .menu-item:has(b:text-matches('^Document')) .default-tag").count()==1); await pg.mouse.click(5,940)
    # ---- imports keep natural type
    await pg.click(".list-head button:has-text('New')")
    async with pg.expect_file_chooser() as fc: await pg.click("text=Import file…")
    await (await fc.value).set_files([os.path.join(F,x) for x in ["Project_Brief.docx","Formulas.xlsx","grades.csv","plain.txt","script.py","page.html","todo.md","Review.pptx"]])
    await pg.wait_for_timeout(300); await pg.screenshot(path=f"{D}/04-import.png")
    await pg.click("button:has-text('Import'):not(:has-text('file'))"); await pg.wait_for_function("!document.querySelector('.modal')", timeout=60000)
    N={n["title"]:n for n in await notes(pg)}
    ok("Word → Document", N["Project Brief"].get("format")=="rich" and "<table>" in N["Project Brief"]["html"] and "data-asset" in N["Project Brief"]["html"])
    fx=N["Formulas"]; ok("Excel → Spreadsheet with formulas", fx.get("format")=="sheet" and fx["sheets"][0]["rows"][3][3]=="=SUM(D2:D3)", str(fx.get("sheets",[{}])[0].get("rows",[[]])[3][:4] if fx.get("sheets") else fx.get("format")))
    ok("CSV → Spreadsheet", N["grades"].get("format")=="sheet")
    ok("Text → Plain text", N["plain"].get("format")=="text")
    ok("Python → Code (python)", N["script.py"].get("format")=="code" and N["script.py"].get("lang")=="python")
    ok("HTML → Document, script removed", N["page"].get("format")=="rich" and "script" not in N["page"]["html"])
    ok("Markdown stays Markdown", N["todo"].get("format")=="markdown")
    ok("PowerPoint → Document", N["Review"].get("format")=="rich" and "Quarterly Review" in N["Review"]["html"])
    await pg.locator(".note-card").filter(has_text="Formulas").first.click(); await pg.wait_for_timeout(500)
    ok("Imported Excel formula computes", (await pg.locator("[data-cell='3-3']").inner_text()).strip()=="130")
    await pg.locator(".note-card").filter(has_text="Project Brief").first.click(); await pg.wait_for_timeout(800)
    ok("Imported Word image shows", await pg.evaluate("Math.max(0,...[...document.querySelectorAll('.rich-doc img')].map(i=>i.naturalWidth))")>0)
    await pg.screenshot(path=f"{D}/05-word-doc.png")
    # alternative choice in import dialog
    await pg.click(".list-head button:has-text('New')")
    async with pg.expect_file_chooser() as fc: await pg.click("text=Import file…")
    await (await fc.value).set_files(os.path.join(F,"Project_Brief.docx")); await pg.select_option(".import-row select","markdown")
    await pg.click("button:has-text('Import'):not(:has-text('file'))"); await pg.wait_for_function("!document.querySelector('.modal')")
    ok("Import can choose Markdown instead", (await cur(pg)).get("format")=="markdown")
    # mobile single pane for markdown
    m=await ctx.new_page(); await m.set_viewport_size({"width":390,"height":844}); await m.goto(BASE); await m.wait_for_timeout(700)
    await m.locator(".note-card").filter(has_text="todo").first.click(); await m.wait_for_timeout(400)
    ok("Phone: Markdown opens one pane (Edit)", await m.locator("[role=radio][aria-checked=true]:text-is('Edit')").count()==1)
    await m.locator(".note-card").count()
    await m.screenshot(path=f"{D}/06-phone.png")
    ok("no errors", not errs, ";".join(errs[:3]))
    await b.close()
asyncio.run(main())
